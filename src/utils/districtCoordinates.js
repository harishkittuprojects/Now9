// Haversine distance formula in kilometers
function calculateDistance(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

// Find closest district in Telangana or Andhra Pradesh for any GPS coordinate
export function findNearestDistrict(lat, lon) {
  let closestDistrictId = "hyderabad";
  let minDistance = Infinity;

  for (const [id, district] of Object.entries(districtCoordinates)) {
    const dist = calculateDistance(lat, lon, district.lat, district.lon);
    if (dist < minDistance) {
      minDistance = dist;
      closestDistrictId = id;
    }
  }

  const result = districtCoordinates[closestDistrictId];
  return {
    districtId: closestDistrictId,
    districtName: result.name,
    stateKey: result.state,
    stateName: result.state === "telangana" ? "Telangana" : "Andhra Pradesh",
    distanceKm: Math.round(minDistance),
    coordinates: { lat, lon }
  };
}
